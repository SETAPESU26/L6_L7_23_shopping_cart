import os
from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Image as RLImage, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

pdf_filename = 'Lab7_FuzzTesting_Deliverable.pdf'
doc = SimpleDocTemplate(
    pdf_filename,
    pagesize=letter,
    leftMargin=0.5*inch,
    rightMargin=0.5*inch,
    topMargin=0.5*inch,
    bottomMargin=0.5*inch
)

styles = getSampleStyleSheet()
title_style = ParagraphStyle(
    'DocTitle',
    parent=styles['Heading1'],
    fontName='Helvetica-Bold',
    fontSize=18,
    leading=22,
    textColor=colors.HexColor('#1a365d'),
    alignment=1,
    spaceAfter=6
)
subtitle_style = ParagraphStyle(
    'DocSubtitle',
    parent=styles['Normal'],
    fontName='Helvetica-Bold',
    fontSize=12,
    leading=15,
    textColor=colors.HexColor('#2b6cb0'),
    alignment=1,
    spaceAfter=10
)
section_style = ParagraphStyle(
    'SectionHeading',
    parent=styles['Heading2'],
    fontName='Helvetica-Bold',
    fontSize=12,
    leading=15,
    textColor=colors.HexColor('#2c5282'),
    spaceBefore=8,
    spaceAfter=4
)
body_style = ParagraphStyle(
    'BodyTextCustom',
    parent=styles['Normal'],
    fontName='Helvetica',
    fontSize=9.5,
    leading=13,
    textColor=colors.HexColor('#2d3748'),
    spaceAfter=6
)

story = []

# Title & Metadata
story.append(Paragraph('PES University — Department of Computer Science &amp; Engineering', subtitle_style))
story.append(Paragraph('LAB 7: Fuzzing for Input Validation Bugs — Deliverable Report', title_style))
story.append(Paragraph('<b>Course:</b> Software Engineering Lab (SELab) &nbsp;|&nbsp; <b>Topic:</b> Property-Based Fuzz Testing with Hypothesis', body_style))
story.append(HRFlowable(width='100%', thickness=1.5, color=colors.HexColor('#2b6cb0'), spaceBefore=4, spaceAfter=8))

# Objective
story.append(Paragraph('1. Objective &amp; Overview', section_style))
story.append(Paragraph(
    'The objective of this lab is to use the <b>Hypothesis</b> library in Python to perform property-based fuzz testing '
    'on a shopping cart application. Hypothesis automatically generates randomized, unexpected, and malformed inputs '
    '(such as empty strings, NoneType values, unicode characters, negative values, and syntax anomalies) to expose hidden crashes '
    'and input validation vulnerabilities, which are then systematically resolved using defensive programming.',
    body_style
))

# Step 2
story.append(Paragraph('2. Step 2: Running the Buggy Application', section_style))
story.append(Paragraph(
    'The initial application was executed using normal sample inputs for cart_total, promo_percent, and delivery_zone. '
    'While it functions on perfect inputs, it completely lacks defensive validation against real-world edge cases.',
    body_style
))
if os.path.exists('step2_buggy_processor_output.png'):
    img = RLImage('step2_buggy_processor_output.png', width=7.0*inch, height=1.9*inch)
    story.append(img)
story.append(Spacer(1, 8))

# Step 3 & 4
story.append(Paragraph('3. Step 3 &amp; 4: Hypothesis Fuzz Test Suite &amp; Test Failures', section_style))
story.append(Paragraph(
    'Fuzz test cases were implemented using the <code>@given(st.text() | st.none())</code> strategy to assert that '
    'functions do not crash on arbitrary input. Running <code>pytest</code> exposed multiple critical failures: '
    'empty string crashes, NoneType attribute errors, unmapped zone key errors, and string unpacking crashes.',
    body_style
))
if os.path.exists('step4_fuzz_tests_failing.png'):
    img = RLImage('step4_fuzz_tests_failing.png', width=7.0*inch, height=2.8*inch)
    story.append(img)
story.append(Spacer(1, 8))

# Step 5
story.append(Paragraph('4. Step 5: Defensive Programming Hardening &amp; Fixed Application Execution', section_style))
story.append(Paragraph(
    'The script was hardened with type checks, null guards, safe string tokenization, non-negative integer parsing, '
    'and safe dictionary lookup defaults. Normal execution continues to work seamlessly on valid inputs:',
    body_style
))
if os.path.exists('step5_fixed_processor_output.png'):
    img = RLImage('step5_fixed_processor_output.png', width=7.0*inch, height=1.9*inch)
    story.append(img)
story.append(Spacer(1, 8))

# Step 6
story.append(Paragraph('5. Step 6: Re-running Fuzz Tests (100% Passed)', section_style))
story.append(Paragraph(
    'Re-running <code>pytest test_shopping_cart.py</code> confirmed that all test cases passed cleanly across hundreds of '
    'randomized inputs generated by Hypothesis with zero crashes.',
    body_style
))
if os.path.exists('step6_fuzz_tests_passing.png'):
    img = RLImage('step6_fuzz_tests_passing.png', width=7.0*inch, height=1.4*inch)
    story.append(img)
story.append(Spacer(1, 8))

# Summary Table
story.append(Paragraph('6. Summary of Vulnerabilities &amp; Defensive Fixes', section_style))
table_data = [
    ['Function', 'Vulnerabilities Uncovered by Hypothesis', 'Defensive Hardening Implemented'],
    ['cart_total(cart)', 'NoneType has no split; ValueError unpacking; ValueError int conversion', 'Type/null check; safe 2-part split guards; int validation; skip malformed'],
    ['promo_percent(code)', 'NoneType has no upper; IndexError on split; ValueError on non-digit', 'Type/null check; check for OFF token; digit parser with fallback 0'],
    ['delivery_zone(pincode)', 'TypeError on None[0]; IndexError on empty string; KeyError on unmapped digit', 'Type/null check; non-empty guard; dict .get() with fallback "Unknown"']
]
t = Table(table_data, colWidths=[1.6*inch, 2.7*inch, 2.7*inch])
t.setStyle(TableStyle([
    ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#2c5282')),
    ('TEXTCOLOR', (0,0), (-1,0), colors.whitesmoke),
    ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
    ('FONTSIZE', (0,0), (-1,0), 8),
    ('BOTTOMPADDING', (0,0), (-1,0), 4),
    ('BACKGROUND', (0,1), (-1,-1), colors.HexColor('#f7fafc')),
    ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e0')),
    ('FONTNAME', (0,1), (-1,-1), 'Helvetica'),
    ('FONTSIZE', (0,1), (-1,-1), 7.5),
    ('VALIGN', (0,0), (-1,-1), 'TOP'),
]))
story.append(t)

doc.build(story)
print('PDF generated successfully:', pdf_filename)
